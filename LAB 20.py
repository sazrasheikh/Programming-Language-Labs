def reverse_Matrix(matrix):
  r,c=np.shape(matrix)
  new_array=np.zeros((r,c),dtype=int)
  counter=c-1
  counter1=r-1
  for i in range(r):
    counter=c-1
    for j in range(c):
      new_array[counter1][counter]=matrix[i][j]
      counter-=1
    counter1-=1
  return(new_array)

