def compress_matrix(mat):
  r,c=np.shape(mat)
  returned_array=np.zeros((r//2,c//2),dtype=int)
  for i in range (0,r,2):
    for j in range (0,c,2):
      returned_array[i//2,j//2]=mat[i,j]+mat[i,j+1]+mat [i+1,j]+mat[i+1,j+1]
  return returned_array


